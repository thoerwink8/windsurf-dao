// dao-rhythm.js — 心跳唤醒的投递点（UserPromptSubmit）
//
// 改这个文件前必须知道的三条：
//
// 1. **它只做一件事**：认出「这一轮是定时唤醒醒来的那一轮」，把长窗留守四句 + 一条 Read 指令
//    注入到那一轮的上下文里。心跳轮是这份载荷**唯一**的投递时刻——用户已经去睡了，
//    没有别人会在那一刻把它递过来。这是宿主没有、文字层替代不了的能力（蓝图件 4）。
//    2026-08-12 三问梳理删掉了另外四支（回顾提醒 / 新建项目提醒 / 收尾提醒 / 自我播报）：
//    它们都是靠猜用户说话方式触发的软提醒，属概率层，值一行偏好不值一个进程。
//
// 2. **判据只对 `String(prompt).trim()` 求值，且排在所有早退之前。** 别加「太短就跳过」
//    「以 / 开头就跳过」这类前置——那些判据一旦改动，心跳轮就可能悄悄落进某个早退分支，
//    而「没注入」与「注入了没照做」在日志上长得一模一样。不给不对齐留机会。
//
// 3. **不做 per-session 去重。** 留守四句要的就是**每一轮都到**：心跳轮之间隔着十几分钟和
//    一整批工具调用，去重等于让第二轮之后的心跳全部裸奔，而那正是本信号要治的病。
//
// 任何异常一律 exit 0 优雅降级（只增不阻）。无信号即无动作，不污染上下文。

const fs = require("fs");

let raw = "";
try { raw = fs.readFileSync(0, "utf8"); } catch (_) {}

let input = {};
try { input = JSON.parse(raw); } catch (_) {}

const prompt = String(input.prompt || "");

// 心跳签名。注入内容里的 `[dao-rhythm WAKEUP v1]` 是取证串：要问「它到底送到没有」，
// 靠 Grep transcript 找这个串，而不是问 agent 本人（自陈不算证据）。
const HEARTBEAT_SIG = /^\[dao-heartbeat\]/;

if (HEARTBEAT_SIG.test(prompt.trim())) {
  process.stdout.write(JSON.stringify({
    hookSpecificOutput: {
      hookEventName: "UserPromptSubmit",
      additionalContext:
        "【dao 节律·WAKEUP】[dao-rhythm WAKEUP v1]\n" +
        "醒来第一动作:Read `ccswitch/rules/dao-longwindow.md` §心跳对账节,按节内次序逐条对账。" +
        "该文件是全文真相源,下面四句只是压缩投影,冲突一律以该文件为准。\n" +
        "㈠心跳·防停摆:监督信号必须独立于作业信道——只靠 task-notification 驱动、任何一路将沉默即饿死整窗;" +
        "故心跳不许断(除了明确 stop:true 的那一轮),且**醒来先对账不凭印象**(在途任务查台账,不查记忆)。\n" +
        "㈡收官简报铁序:**简报先行**(先于心跳设置、作为独立完整消息发出)· **禁预记**(心跳 prompt 只准写未来动作," +
        "不准预记「已发」)· **ScheduleWakeup 是本轮刻意的最后动作**,调用前简报与全部实质动作须已完成" +
        "(它一返回轮就终结)。\n" +
        "㈢在途水位线:默认态是**多路满载**,单路在途是需要理由的例外——不是反过来;" +
        "**补水位排在本轮第一个工具段**,在任何 merge/裁决/抽验之前。" +
        "判据一句话:每个「不派」都要答得出「这一路为什么不能现在跑」,答不出就是水位缺口。\n" +
        "㈣自主边界(永不进自主窗):**不可逆决策**(架构定死/对外发布/删用户数据)· " +
        "**需用户在场件**(凭据/审美拍板/真钥)· **用户未点头的新疆域**——三格一律不进," +
        "只做「沿既定方向推进+健康维护」,转向权归用户。",
    },
  }));
}

process.exit(0);
