// 段首取命令名：剥掉 `sudo`/`time`/`command`/`nohup` 前缀与路径、`.exe` 后缀，转小写。
// **刻意不剥 `until`/`while`/`if`/`for`/`do`/`then`** —— 那些构造下的 `grep -q ... ` 是**轮询/判断**，
