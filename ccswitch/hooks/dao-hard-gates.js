//    中间任何取值（如 63/64/65）的行为面都没有断言在量，只有常量文本被改动时会红。
const G2_CAND_STARVE_N = 64;

// 多相判定。**判决 = 相①（归一前）∨ 相②（归一后）∨ 相③（8.3 投机展开），任一命中即拦；
// 都不中而且「有候选压根没验过」时按饿死 fail-close。**
//
// 🔴 **函数名 2026-08-09（#214）由 `g2TwoPhase` 改成 `g2Phases`**，作废原名照录：
//    ~~`function g2TwoPhase(judge)`~~ —— 本批加了相③，一个叫「两相」的函数跑三相就是
//    下一个人会照字面相信的假话。**改名让每个引用点都必须被看一眼**（回归网锚点会当场红）。
//
// 🔑 **它顺带把「同一个病的第 3、4 种长相」结构性消掉了**（头注 ⑯⑰）：那个病是
//    「**用归一后的值去做归一前的字符串假设**」—— 快筛问末段，而归一（realpath）会改写末段。
//    此前两次修法都是给**被发现的那一道**快筛加「也看归一前」的特例，于是它换了个长相
//    （目录 → 文件名）又活了一次。**相① 压根不归一**，末段就是用户写的那个末段
//    ⇒ 不存在「归一改写末段」这件事。**补的是深度，不是某一道筛。**
// 🔑 **相① 拦下就不起子进程**：真违例的常见形态（`~/.claude/settings.json`、
//    `$env:USERPROFILE\.claude\settings.json`）在相① 就命中 ⇒ **一次 I/O 都不落**。
// ⚠️ **三相都要跑，别「优化」掉任何一相**：相① 独有的覆盖面是「末段被链改写」那一类
//    （头注 ⑰：`settings.json` 自己是符号链接）；相② 独有的是「候选路径里有链、只有真
//    realpath 解得开」那一类；相③ 独有的是「realpath **没验成**，而候选是 8.3 短名形态」
//    那一类（＝ ⑱ 那条回归带）。回归网三侧各有专属样本 + 各一条 mutation 钉着。
//
// 🔴 **相③ 与饿死 fail-close 是 #214 的两半，缺一不可**（issue #214 / PR #216 对抗判词）：
//    批量子进程是**一批候选共享一个时间界**，候选数量够大时排在后面的**压根轮不到**
//    ⇒ 退回「按原样比」⇒ 真目标漏过。实测回归带：本机 N≈32000 起，同一条命令
//    改动前（逐条独立同步解析、无共享预算）拦得住，#199 那一版漏过。
//    · **相③** 治「短名形态」那一大类：不靠 I/O 也说得出「这条可能就是 live 的短名写法」。
//    · **饿死 fail-close** 治剩下那一类（候选路径里有链、只有真 realpath 解得开）：
//      **相③ 展开不出来 + 这条候选压根没验过 + 本批候选数已经不是日常形态** ⇒ 不许静默 exit 0。
//      「没验完」与「没有违例」在退出码上长得一模一样，而这道闸的整个价值就在于两者不同。
// ⚠️ **fail-close 只开在这一格，别读成「G2 改成 fail-closed 了」**：设计取舍② 仍然成立 ——
//    单条候选解不开（文件不存在 / 毒路径卡住 / 界收得太紧）照旧 fail-open，因为那一格的误伤
//    代价是真的（PR #145 第三轮实测：一次 `ENAMETOOLONG` 就把合法的项目级
//    `.claude/settings.json` 从 0 翻 2，而 G2 的逃生阀只有用户设得了 ⇒ 撞上即会话卡死）。
//    这一格要同时满足**没验完**且**候选数 > `G2_CAND_STARVE_N`**，而后者在日常形态上是 0-3。
// `blocked(what)` 由调用方给 —— 相③ 的直判路不重跑 judge，拦截文案的三条正路那一半
// 仍须与两个分支逐字同一份（那份文案是判据的一部分，抄第二份必漂移）。
//
// ── #214 ㉑：相③「重跑 judge」那条路的开销上界（2026-08-09 · PR #235 对抗官第三代实测坐实）──
// **它是怎么被摸出来的**：相③ 的 `dirForm` 分支会把整条判定跑第三遍（对 shell 分支：把全部
// segment 重新走一遍 `g2WriteTargets`），首版**没有任何上界** —— 开关握在攻击者手里，只需
// 再塞一个「展开后恰是 live 目录本身」的候选（末位放，让它落进 `batch.untried`）即可打开。
// 实测（N=48000 诱饵）：不带这个 token 5.3 s、带上 11.4 s ⇒ 越过宿主给这个 hook 的 10 s
// ⇒ **整个 hook 被杀，七道闸一起放行**——包括那条本该被饿死 fail-close 拦下的命令。
// 完整论证见上方 ㈡ 那段（作废原文与订正都在那里），这里只记常量与判据。
const G2_HOST_TIMEOUT_MS = 10000;    // 宿主对本 hook 的注册超时（config-sync 快照里
                                      // `hooks.PreToolUse[].timeout`，单位秒，这里换算成 ms）。
                                      // 只读它来算「还剩多少预算」，**不是它的真相源**——改注册
                                      // 值不会同步到这里，取不准的方向刻意保守。
const G2_RERUN_SAFETY_MARGIN_MS = 2000;  // signal 投递 / stderr 写出 / 进程退出的开销边际。
                                          // 判断档，AI 自定，已在 PR body 列为可退回项——嫌紧
                                          // 或松都只改这一个数。
                                          // 🔴 **口径订正（issue #254）**：此处原注释写「留给
                                          // v1CostMs 低估 v3 真实代价的那一截」——那一截现在由
                                          // `G2_RERUN_COST_FACTOR`（见下）直接校正，不再是这个
                                          // 常量单独兜底；这个常量现在只兜 signal/stderr/进程
                                          // 退出那部分固定开销 + 系数没覆盖到的残余低估。
const G2_RERUN_DEADLINE_MS = G2_HOST_TIMEOUT_MS - G2_RERUN_SAFETY_MARGIN_MS;
// ㉑ **预算闸的估价系数**（issue #254，用户 2026-08-09 拍板 =2.5×，出处 issue #70 评论
// 5231799900）：相① 的真实耗时（`v1CostMs`）不再原样当"重跑一遍要多贵"的估价，先乘这个
// 系数再比。**为什么要乘它**：对抗官第三代 12 组样本实测 v3/v1 = 1.88–2.64（均值 ≈2.22），
// 原判据把这个比值当"约等于 1"，在 v1∈(2.8s,3.5s)（本机约 N≈40000–52000）这一段会误判
// "还来得及"（issue #254 的实测坐实，完整推导见上方 ㉑ 头注）。**系数取值是判断档，本次
// 数值由用户拍板、非 AI 自定**——回测口径：同一批 12 样本下 N=40000/44000/48000（原危险窗
// 内）全部拦下、N=32000 仍放行（总墙钟 7.6 s，在预算内）。
const G2_RERUN_COST_FACTOR = 2.5;
function g2Phases(judge, blocked) {
  const t0 = Date.now();   // ㉑ 预算闸的起点——量的是「这一次 g2Phases 调用」的墙钟，不是
                            // 整个 hook 进程的墙钟（G1 的开销可忽略不计，见 ㉑ 上方论证）。
  const wanted = [];
  const seen = new Set();
  const v1 = judge((p) => {
    if (!seen.has(p)) { seen.add(p); wanted.push(p); }
    throw new Error("G2 相①：本相不落 I/O");
  });
  if (v1) return v1;
  // ㉑ **这一次相① 的真实耗时，当"再跑一遍要多贵"的估价**——它与相③ 的重跑做的是同一件事
  // （把全部 segment 重新走一遍 `g2WriteTargets`），量级天然接近，且随机器速度/payload 大小
  // 自动跟着变，不需要为换机再调一次常量。**它是估价不是精确解**：v3 的 `rp` 闭包比 v1 的
  // 「一律抛」多做 Map 查找 + `g2ShortExpand` 调用，~~实测代价略高于 v1~~
  // ~~🔴 **订正（对抗官第三代实测证伪，issue #254）**：12 组样本实测 v3/v1 = 1.88–2.64，均值
  // ≈2.22——不是"略高"，是约 2.2 倍。故留了安全边际（`G2_RERUN_SAFETY_MARGIN_MS`）兜这一截
  // 低估，但当前 2000ms 的边际不足以兜住 2.2 倍的低估，实测窗口见 ㉑ 头注。~~
  // ✅ **已修（issue #254）**：12 组样本实测 v3/v1 = 1.88–2.64（均值 ≈2.22）这个数没变，变的
  // 是拿它怎么用——不再指望安全边际硬扛这截低估，改乘 `G2_RERUN_COST_FACTOR`（=2.5，用户
  // 2026-08-09 拍板）直接校正，判据见下方 `elapsed + G2_RERUN_COST_FACTOR * v1CostMs >
  // G2_RERUN_DEADLINE_MS` 那一行。
  const v1CostMs = Date.now() - t0;
  if (!wanted.length) return null;          // 没有任何候选想 realpath ⇒ 零 I/O 收工
  const batch = g2RealpathBatch(wanted);
  const starved = batch.fed - batch.tried;  // 压根没轮到的那些（≠「试过但文件不存在」）
  if (starved > 0) {
    // **fail-open / 降级都不许静默**（同常量侧那行自陈）。射程一样照直写：宿主对 exit 0 的
    // stderr 不回喂给 agent ⇒ 它是给读日志的人看的，判决通道仍然只有退出码。
    process.stderr.write(
      `[dao-hard-gates G2] ⚠ 候选侧批量 realpath 没跑完：喂进去 ${batch.fed} 条、只解到第 ` +
      `${batch.tried} 条（界 ${G2_CAND_REALPATH_MS}ms/批）⇒ 还有 ${starved} 条**这次没验过**。` +
      `相③ 会对其中 8.3 短名形态的做零 I/O 投机展开；展开不出来的那些**是「没验」不是「没事」**。\n`);
  }
  if (batch.map.size) {
    const v2 = judge((p) => {
      const v = batch.map.get(p);
      if (!v) throw new Error("G2 相②：这一条没解开");
      return v;
    });
    if (v2) return v2;
  }
  // ── 相③（#214）：只对**压根没轮到**的候选做 8.3 投机展开 ─────────────────────────
  //    🔴 **射程是 `batch.untried` 不是「map 里查不到的」**，这一格实测过、别放宽：
  //    「试过了、文件系统说没有」（ENOENT，写新文件的常态）与「压根没轮到」在旧返回值里
  //    长得一样，而前者改动前就是 fail-open ⇒ 把过近似铺到它上面等于凭空造一格新误伤
  //    （首版就是这么写的，被回归网那条「`…~9` 在真界下不许拦」当场逮住）。
  // 🔴 **它刻意分成「直判」与「重跑 judge」两条路，不是一律重跑**（实测逼出来的）：
  //    第三遍 judge 要把整条命令的分段与目标位合成重走一遍，2.8 MB payload 上那一遍
  //    **单独就值 4.7 s**（首版把 hook 寿命由 5.0 s 顶到 9.7 s，宿主 10 s 预算差点烧掉，
  //    而那正是 #133/#199 两批一直在守的东西）。⇒ 能不重跑就不重跑：
  //    ㈠ **直判**：某条没验过的候选，展开后**自己就是一条 live 文件路径** ⇒ 判决已经确定，
  //       直接出拦截，不必再跑 judge（⑱ 那条回归带走的就是这条路）。
  //    ㈡ **重跑**：展开后是 live **目录**（`cp <源> <目标目录>` 那一支合成的候选是
  //       「目标目录 + **源**文件名」）⇒ 拦不拦还要看那一段的源文件名叫什么，只有 judge
  //       知道 ⇒ 这一格才重跑第三遍。
  //       🔴 **下一句是枚举式笃定，2026-08-09（PR #235 对抗官第三代）实测证伪，作废原文照录**
  //       （`#官通-禁笃定措辞`）：~~它的触发条件很窄（展开结果恰是 live 目录本身），日常与
  //       本批实测的攻击 payload 都走不到。~~ —— 「日常走不到」对**本批自己构造的** payload
  //       成立，对**攻击者自己挑的** payload 不成立：只需再塞一个「展开后恰是 live 目录本身」
  //       的候选（末位放，让它落进 `batch.untried`）即可打开这条路，而这道闸的威胁模型里
  //       payload 本来就是攻击者挑的。**实测**：N=48000 诱饵 + 一个末置触发子，同一条 payload
  //       从 5.3 s 顶到 11.4 s ⇒ 越过宿主 10 s ⇒ **整个 hook 被杀，七道闸一起放行**——包括
  //       那条本该被饿死 fail-close 拦下的命令。这条路的开关握在攻击者手里，它必须有自己的
  //       开销上界，不能靠"触发条件窄"当天然护栏。**修法（㉑，见下方预算闸三常量与本函数内
  //       `elapsed + G2_RERUN_COST_FACTOR * v1CostMs > G2_RERUN_DEADLINE_MS` 那一行）**：用
  //       **这一次真实测得的相① 耗时**当"重跑一遍要多贵"的估价——相③ 的重跑与相① 做的是同一
  //       件事（把全部 segment 重新走一遍 `g2WriteTargets`），量级天然接近，且随机器速度/
  //       payload 大小自动跟着变，不需要为换机再调一次常量。预算不够就不硬跑，退回**饿死
  //       fail-close**（诚实说"没验完"，不是"查过没事"），不静默放行、不起任何进程：①墙钟
  //       有界——~~这条检查本身就是为了不让 v3 把总时长推过宿主界~~
  //       ~~🔴 **射程限定（对抗官第三代实测证伪，issue #254）**：上一句是无射程限定的笃定话——
  //       它只在**闸真的判定"预算不够"时**成立；闸自己的估价会把 v3 代价低估约 2.2 倍，故在
  //       一段 N 上（本机 N≈40000–52000）闸判"还来得及"、实际仍会越宿主 10 s 界，这条检查在
  //       那一段**不构成总墙钟的硬上界**，只是把被杀的窗口相对推远了。真正的硬上界要等估价
  //       系数修好（issue #254）才成立；②解不开不静默退化——走的是既有的 `g2Starved`；
  //       ③孙进程产不出——纯 JS 时间戳比较，不涉及任何 spawn。~~
  //       ✅ **系数已修（issue #254，用户 2026-08-09 拍板 =2.5×）**：上一句「不构成总墙钟的
  //       硬上界」的成因已被校正——估价不再是 v1CostMs 原样，而是乘 `G2_RERUN_COST_FACTOR`
  //       后再比，原危险窗（v1∈(2.8s,3.5s)，本机约 N≈40000–52000）内的 12 组回测样本
  //       （N=40000/44000/48000）均已正确拦下；②③两条不受这次改动影响，原样成立。**这句话
  //       的射程边界同样要照直写**：它证的是「已回测的这批样本」，不是「v3/v1 这个比值再无
  //       更大离群值」——见 ㉑ 头注「未尽处」段。
  if (batch.untried.length) {
    const syn = g2LiveDirSyntactic(), real = g2LiveDirReal();
    const expand = (p) => g2ShortExpand(p, syn, real);
    const untried = new Set(batch.untried);
    let direct = null, dirForm = false;
    for (const p of batch.untried) {
      const g = expand(p);
      if (!g) continue;
      if (g2IsLive(g)) { direct = { p, g }; break; }
      if (g === syn || g === real) dirForm = true;
    }
    if (direct) {
      return blocked(
        `要写用户级 live 配置 —— 候选 \`${direct.p}\` 的 8.3 短名投机展开是 \`${direct.g}\`` +
        `（相③：这一条压根没轮到 realpath，故按短名规则反推）`);
    }
    if (dirForm) {
      // ㉑ **预算闸**：重跑一遍 judge 的代价用 `v1CostMs × G2_RERUN_COST_FACTOR` 估价
      // （issue #254·2026-08-09 用户拍板系数=2.5×，出处 issue #70 评论 5231799900——
      // 12 组样本实测 v3/v1 均值 ≈2.22，系数取值与回测口径见该常量正上方注释），预算不够
      // 就不硬跑——退回饿死 fail-close（诚实说"没验完"），不是静默放行、也不是不管三七二十一
      // 硬跑到宿主把整个 hook 杀掉（那样连这一格 fail-close 本身都没机会说出口）。
      const elapsed = Date.now() - t0;
      if (elapsed + G2_RERUN_COST_FACTOR * v1CostMs > G2_RERUN_DEADLINE_MS) return g2Starved(batch.fed, starved);
      const v3 = judge((p) => {
        const v = batch.map.get(p);
        if (v) return v;                      // **精确优先**：解开过的候选不吃过近似
        const g = untried.has(p) ? expand(p) : null;
        if (g) return g;
        throw new Error("G2 相③：既没解开、也做不出 8.3 投机展开");
      });
      if (v3) return v3;
    }
  }
  // ── 饿死 fail-close（#214）：三相都没拦下，而这一批里有候选压根没验过 ────────────────
  if (starved > 0 && batch.fed > G2_CAND_STARVE_N) return g2Starved(batch.fed, starved);
  return null;
}

// 饿死那一格的拦截文案。**它说的不是「查出你在写 live 配置」，是「这次没查完」** ——
// 两件事分开说，否则被拦的人会去找一个并不存在的违例目标。
function g2Starved(fed, starved) {
  return {
    what:
      // 🔴 **口径订正（2026-08-09 · PR #235）**：此处此前写「${fed} 个待归一的**写目标**」，
      //   而 `fed` 计的是归一候选（`wanted`），一个写目标最多进候选两次（整条 + 父目录退化
      //   一级）⇒ 写目标数≈候选数的一半。旧文案会让写了 33 个目标的人看见「66」，把自己以为
      //   触发的阈值读大一倍。改成明说「候选」并给出与写目标的换算关系。
      `一条命令里产生了 ${fed} 条待归一的候选（每个写目标最多计 2 条：整条路径 + 父目录退化` +
      `一级，故候选数 ≈ 写目标数的 2 倍），界内只验完 ${fed - starved} 条 ` +
      `⇒ 还有 ${starved} 条**这次没验过**（不是「验过没事」）`,
    how:
      "这一格是 **fail-close**，理由是它与别处不同：候选侧那次归一是**一批共享一个时间界**的，" +
      "候选数量够大时排在后面的压根轮不到 ⇒ 退回「按原样比」就会把真目标放过去" +
      "（issue #214 的回归带，实测同一条命令改动前拦得住）。**「没验完」不等于「没有违例」。**" +
      "正路二选一：①**把这条命令拆小**——一条命令里几十上百个 8.3 短名写目标不是日常形态，" +
      "日常形态是 0-3 个；②确实要一次写这么多、且确认不碰 `~/.claude/settings.json` 时，" +
      "由**用户**设 `DAO_SETTINGS_EDIT_APPROVED=1` 后重开会话（agent 自己 export 影响不到本 hook）。",
  };
}

const _g2LiveDirCache = { syn: null, real: null };
// ① 语法层：零 I/O
function g2LiveDirSyntactic() {
  if (_g2LiveDirCache.syn === null) {
    _g2LiveDirCache.syn = norm(path.join(HOME, ".claude")).toLowerCase();
  }
  return _g2LiveDirCache.syn;
}
// ② realpath 层：有 I/O，**只在语法层没命中时才求值**。
// **惰性 + 记忆化在这一版是安全的**（#133）：它的输入与 payload 无关，而且没有任何会被
// 耗尽的共享资源 —— 第三轮那条绕过靠的正是「诱饵先把预算打死，再让这一格退回未归一值」，
// 而预算已经不存在了 ⇒ 惰性求值这次没法被反过来用。
function g2LiveDirReal() {
  if (_g2LiveDirCache.real === null) {
    // 零 I/O 归一（`//?/` 前缀 / `..` / `.` / 重复分隔符）—— 这一步刻意不落 I/O，
    // 故传恒抛的 `G2_RP_NONE`，realpath 那一步下面单独做。
    const syn = g2Canon(norm(path.join(HOME, ".claude")), G2_RP_NONE);
    // 🔴 **无条件过一次有界 realpath（2026-08-09 · #199，头注 ⑯ 相邻格）**。作废原文照录：
    //   ~~`_g2LiveDirCache.real = g2Canon(norm(path.join(HOME, ".claude")), g2RealpathBounded).toLowerCase();`~~
    //   —— 那一版借的是 `g2Canon` 里「**含 `~N` 才解**」这个条件，而那个条件是
    //   **候选侧为了省 I/O** 才有的。常量侧每进程最多算一次，省不出什么，
    //   却让「`~/.claude` **自己是链**」这一格在**长名 HOME** 上两侧一起漏：
    //   攻击者直接写链目标路径（`<home>\actualcfg\settings.json`）即可，
    //   **写长名反而不会被抓**（第三轮 6a/6b 实测 master 与 PR #197 版都是 exit 0）。
    //   现在常量侧拿得到真实目录 ⇒ 那条路径与它精确比得上。
    // 🔑 **它没有把「N × timeout」搬到这一侧**：输入仍然是 `path.join(HOME, ".claude")`，
    //   与 payload 无关、记忆化后每进程最多求值一次。变的只是「什么时候解」，不是「解几次」。
    let solved = 0;
    _g2LiveDirCache.real = norm(g2LongPath(syn, (p) => {
      const v = g2RealpathBounded(p);
      solved++;
      return v;
    })).toLowerCase();
    // **fail-open 不许静默**（设计取舍②）：一次都没解成 ⇒ 本次是拿**未归一**的 HOME 在比，
    // 8.3 短名家目录 / `.claude` 是链时这道闸此刻是瞎的，
    // 而「瞎」与「没有违例」在退出码上长得一模一样。
    // 🔴 **判据 2026-08-09 换过（#199）**，作废原文照录：~~`if (/~\d/.test(HOME) && /~\d/.test(real))`~~
    //   —— 无条件解析之后，长名 HOME 上的失败**看不出来**（进出都不含 `~N`）⇒ 那个判据会
    //   在新加的那一格上恒假、静默。改成数**成功次数**：`solved === 0` 才是「一次都没验成」。
    // ⚠ 照直写它的射程：宿主对 exit 0 的 stderr 不回喂给 agent（只有 exit 2 才回喂）⇒
    //   它是给**读日志的人**看的，不是一条会被谁读到的告警。判决通道仍然只有退出码。
    if (solved === 0) {
      process.stderr.write(
        `[dao-hard-gates G2] ⚠ 常量侧 realpath 没验成（有界子进程超时或失败，界 ` +
        `${G2_CONST_REALPATH_MS}ms/次）⇒ 本次按未归一的 HOME 比对，8.3 短名家目录或 ` +
        `\`.claude\` 是链时这道闸**可能拦不住** live 配置写入。**这不是「通过」，是「没验」。**\n`);
    }
  }
  return _g2LiveDirCache.real;
}
// 两层依次比。**次序是判据的一部分，别调换**：调换之后第一层的「零 I/O」就白设了。
function g2MatchesLiveDir(low) {
  if (low === g2LiveDirSyntactic()) return true;
  return low === g2LiveDirReal();
}

function g2IsLive(p) {
  if (!p) return false;
  const low = norm(p).toLowerCase();
  return G2_LIVE_NAMES.some((n) => {
    if (!low.endsWith(`/${n}`)) return false;              // 先按文件名快筛，零 I/O
    return g2MatchesLiveDir(low.slice(0, low.length - n.length - 1));
  });
}
// 「这个文件名**有没有可能**落地成 live 那两个文件之一」——纯字符串，零 I/O。
// 两种放行：①名字本身就是（零 I/O 判得出）②它是个 8.3 短名（`~<数字>`，零 I/O **判不出**，
// 放行到 realpath 层定案 —— 本卷上 `settings.json` 的真短名是 `SETTIN~1.JSO`，回归网有正控）。
const g2BaseCouldBeLive = (b) => {
  const low = String(b || "").toLowerCase();
  return /~\d/.test(low) || G2_LIVE_NAMES.indexOf(low) >= 0;
};

// 「这条路径**有没有可能**是 live（或 live 目录）」——纯字符串，零 I/O。
// 🔴 **它是 #199 削掉候选侧放大器的第一刀**：答否 ⇒ 这条候选**一次 realpath 都不试**。
//   放行面刻意宽（含 `.claude` 目录形态与任何 8.3 短名末段），因为它只决定
//   「要不要花那次 I/O」，**拦不拦仍由 `g2MatchesLiveDir` 的精确比对说话** ⇒
//   放宽这里只会多花 I/O，不会多拦一条（回归网有一条反向 mutation 钉住这句话）。
// 🔴 **它必须在 realpath 之前问、在字符串归一之后问**（唯一调用点在 `g2Canon` 里面）：
//   realpath 之后问 = 头注 ⑯⑰ 那个病（归一会改写末段）· 字符串归一之前问 = 2026-08-09
//   实测那条自伤（`::$DATA` / `//?/` 还没剥，末段是个假末段）。两个错法各有实证，见下方。
const g2TailCouldBeLive = (s) => {
  const low = norm(s).toLowerCase();
  const i = low.lastIndexOf("/");
  const tail = i < 0 ? low : low.slice(i + 1);
  return tail === ".claude" || g2BaseCouldBeLive(tail);
};

// 🔴 **前筛必须落在 `g2Canon` 的「零 I/O 串处理之后」，不能落在它之前**（2026-08-09 实测纠正）：
//   首版把它写在 `g2Resolve` 里、拿 `g2ResolvePre` 的产物去筛，**当场打掉一条既有正控** ——
//   `…/.claude/settings.json::$DATA` 的末段是 `settings.json::$data`，既不是 live 名也没有
//   `~N` ⇒ 被筛掉、realpath 不跑、8.3 短名那一格重新漏（`::$DATA` 是 `g2Canon` 里剥的，
//   剥之前问末段等于问了个还没归一完的串）。**同族的还有 `//?/` 前缀与尾空格。**
//   ⇒ 判据一句话：**前筛问的是「归一前」，但那指的是 realpath 前，不是字符串处理前。**
//   （这就是本文件那条透镜的又一次变形：**在错误的深度上问末段**。这次它咬的是我自己，
//   而抓住它的是既有回归网里那条 ADS + 短名的正控 —— 不是我自觉想起来的。）

// 🔴 **`g2IsLiveDir` / `g2DirTailLooksLive` 2026-08-09 删除（#199）**，作废原文的判据照录：
//   ~~目标位给的是 `~/.claude` **目录**时，先问「目标目录的末段像不像 `.claude`」（零 I/O 快筛），
//   像才往下比。#134 给它补了「归一前也算一侧」的第二个深度。~~
//   删它的理由有两条，第二条才是要紧的：
//   ㈠ **它不是承重判据**（原回归网已有一条阴性结果钉着）：它只是少产一批永不命中的候选，
//      把它改成 `if (false) continue;` 一条负控都翻不动 —— 真正定案的是 `g2IsLive`。
//   ㈡ 🔴 **它问的问题本身就是错的**：live 目录的末段**不一定**叫 `.claude`（`~/.claude`
//      是链时真实目录可以叫任何名字）⇒ 它**既拦不住该拦的**（头注 ⑯ 相邻格：写链目标即绕过），
//      **又是「用归一后的值做归一前假设」那个病连着四种长相的载体**。
//   ⇒ 换成 `g2BaseCouldBeLive(源的 basename)`：同样零 I/O、同样只做前筛，
//      但它问的是**源文件名**（与目录是不是链无关），目录侧一律交给精确比对。

// 把 home 的各种变量形态展开成真实路径。
// **替换一律用函数形式**——HOME 是从环境读来的字符串，直接当替换串会让其中的 `$&`/`$1`
// 被 String.replace 当成引用（本机 HOME 里没有 `$`，但那是运气不是判据）。
function g2Expand(raw, vars) {
  let s = String(raw == null ? "" : raw).trim();
  while (/^(["'])([\s\S]*)\1$/.test(s)) s = s.replace(/^(["'])([\s\S]*)\1$/, "$2");
  // 同一条命令内的字面量变量（见下方 g2VarMap）。`$env` 是命名空间前缀不是变量名，跳过。
  if (vars && vars.size) {
    s = s.replace(/\$\{?([A-Za-z_]\w*)\}?/g, (m, name) => {
      if (/^env$/i.test(name)) return m;
      const v = vars.get("$" + name);
      return v == null ? m : v;
    });
  }
  const H = () => HOME;
  return s
    .replace(/\$env:HOMEDRIVE\$env:HOMEPATH/gi, H)          // PowerShell 拼接形态
    .replace(/\$\{env:(?:USERPROFILE|HOME)\}/gi, H)         // ${env:USERPROFILE}
    .replace(/\$env:(?:USERPROFILE|HOME)(?![A-Za-z0-9_])/gi, H) // $env:USERPROFILE ← 本次绕过用的就是它
    .replace(/%HOMEDRIVE%%HOMEPATH%/gi, H)                  // cmd 拼接形态
    .replace(/%(?:USERPROFILE|HOME)%/gi, H)                 // %USERPROFILE%
    .replace(/\$\{(?:HOME|USERPROFILE)\}/g, H)              // ${HOME}
    .replace(/\$(?:HOME|USERPROFILE)(?![A-Za-z0-9_])/g, H)  // $HOME（PowerShell 的 $HOME 同义）
    .replace(/^~(?=[\\/]|$)/, H);                           // ~/...
}

// 8.3 短名（`C:/Users/ADMINI~1/...`）在 path 层面解不开——它是文件系统的别名，只能问文件系统。
// **本机不是理论形态**：全量语料普查 27365 条去重命令里 `~<数字>` 路径 **1196 条**
// （scratchpad 一律走 `C:\Users\ADMINI~1\AppData\...`），而 `ADMINI~1` 正是 HOME 的短名。
// 三条刻意的收窄，别读成"顺手加个 realpath"：
//   ㈠ **只在盘符绝对路径 + 真含 `~<数字>` 时才落 I/O** —— 不这么收窄的话，`//server/share/...`
//      会把网络 SMB 超时（可达数十秒）拖进一个 PreToolUse 钩子里，等于用会话卡死换覆盖面。
//   ㈡ **失败一律按原样比**（fail-open，同头注设计取舍②）：文件还不存在是正常的（Write 新建）。
//   ㈢ 整条解不开时退到**目录级** —— 本机实测 `C:\Users\ADMINI~1\.claude` 解得出，
//      故文件名本身是短名以外的形态都接得住。**⚠ 2026-08-04 订正**：这里原写
//      「（`SETTIN~1.JSON`）」，那个短名**根本不存在** —— 8.3 是 8 位主名 + **3 位**扩展名，
//      `settings.json` 的真短名是 **`SETTIN~1.JSO`**（本机 `dir /x` 实测）。写错的那个是四位扩展名，
//      于是这句话举的例子是个永不出现的字符串 —— 由 #117 对抗验证官查出。
//      **它现在被接住了**（文件名短名同样落 realpath 全路径那一步），回归网有正控钉着。
// ⚠ 它顺带会解开 symlink/junction，这是 realpath 的语义、不是本函数想要的；因为它只在
//   `~<数字>` 路径上跑，而那类路径此前**一律不匹配**，任何改变都只会往"更准"的方向走。
// **realpath 的实现由调用方给**（#133）：🔴 **缺省 2026-08-09 由 `G2_RP_SYNC` 换成
// `G2_RP_NONE`（#199）** —— 即**缺省不落 I/O**，而不是「缺省掉进无界同步 realpath」。
// 现在两个真实现都是有界子进程：常量侧传 `g2RealpathBounded`（单路径、每进程 ≤2 次），
// 候选侧由 `g2Phases` 传相①/相② 那两个闭包（批量、每进程 ≤1 个子进程）。
// 🔴 **刻意做成参数而不是模块级开关**：开关是**有状态**的，而 PR #145 第二、三轮那两条绕过
//    都长在「一个会被改写并缓存一整个进程的降级状态」上。参数没有状态，攻击者也构造不出
//    「让常量侧改用不同实现」的输入。**#199 加了候选侧之后这条更要紧**：两侧各自拿自己的
//    闭包，候选侧那次批量解析**耗不到**常量侧任何东西（第三轮那条绕过正是靠共享资源）。
function g2LongPath(p, rp) {
  const realpath = rp || G2_RP_NONE;
  try { return realpath(p); } catch (_) { /* 文件不存在是常态；有界版超时也走这里 */ }
  try {
    const i = p.lastIndexOf("/");
    if (i > 0) return realpath(p.slice(0, i)) + p.slice(i);
  } catch (_) { /* 目录也不存在 ⇒ 按原样比 */ }
  return p;
}

// 绝对路径归一（issue #112 甲⑨）。**改前这一步整个不存在** —— 只有相对路径过 `path.resolve`，
// 绝对路径原样拿去跟 live 精确比对 ⇒ `..` / `.` / `//` / 8.3 短名 / `\\?\` 全部绕开。
// 🔴 **这一格穿透的是改动前就有的 Edit/Write 分支，不是 shell 分支独有** —— 即 G2 自诞生起就漏。
//
// **为什么按根的形态分派两个归一器，而不是统一用一个**（本机实测逐一验过，别改成"更简洁"的写法）：
//   · `path.posix.normalize("C:/../Users/x")` → `Users/x` —— **把盘符当成普通段吃掉了**，
//     于是 `C:/../Users/Administrator/.claude/settings.json` 归一成一个相对路径、彻底比不上 live。
//     用它处理盘符路径 = 把一个漏报换成另一个漏报。
//   · `path.win32.resolve("/../home/x")` → `D:/home/x` —— **凭空补上当前进程的盘符**，
//     在 HOME 是 POSIX 形态的机器上会把路径改写成别的东西。
//   ⇒ 盘符绝对走 win32.resolve（在盘根处夹住 `..`），POSIX 绝对走 posix.normalize（在 `/` 处夹住）。
// **`//` 开头（UNC）刻意不归一**：posix.normalize 会把前导 `//` 折成 `/`，而那个路径要原样回显
// 给被拦的人看，折了会让人以为闸拦错了对象。UNC 共享形态本来就在覆盖面外（见头注 G2 ⑨）。
//
// **NTFS 备用数据流（2026-08-04 由 #117 对抗验证官查出，本批修）**：`<path>::$DATA` 是 NTFS
// 里**默认数据流的显式写法**，写它就是写原文件本身。本机实测（`_tmp/probe-newgaps.ps1`）：
//   · `settings.json::$DATA`  写入后原文件内容 = HIJACKED  ⇒ **确实改写原文件，是真绕过**
//   · `settings.json:$DATA`   写入后原文件内容 = ORIGINAL  ⇒ 单冒号是**另一条**流，不碰原文件
//   · `settings.json:mystream` 写入后原文件内容 = ORIGINAL ⇒ 具名旁路流，同样不碰原文件
// ⇒ **只剥 `::$DATA` 这一种，且必须锚在末尾**。剥多了就是误伤（把真旁路流当成写原文件）。
// 零误伤面：Windows 文件名里 `:` 本就非法（只作盘符与流分隔符），没有合法文件名以 `::$DATA` 结尾。
// `rp` 只往下传给 `g2LongPath`（#133）：**两侧必须共用同一个归一器**，否则又会掉进
// 「两侧不在同一深度」那个病（#112 阻断项）—— 所以常量侧不另写一套 canon，只换 realpath 实现。
function g2Canon(s, rp) {
  if (!s) return s;
  // Win32 扩展长度前缀是**纯字符串**前缀，剥它不需要任何 I/O：`//?/C:/…` → `C:/…`
  if (/^\/\/[?.]\/[A-Za-z]:\//.test(s)) s = s.slice(4);
  // NTFS 默认数据流的显式写法 ⇒ 等价于原文件（三种流形态的实测差别见上方注释）
  s = s.replace(/::\$DATA$/i, "");
  if (/^[A-Za-z]:\//.test(s)) {
    try { s = norm(path.win32.resolve(s)); } catch (_) { /* 解析不了就按原样比 */ }
    // 🔴 **`g2TailCouldBeLive(s)` 是 #199 的零 I/O 前筛，也是本闸唯一的 I/O 闸门**：
    //   末段不可能是 live 的候选**一次 realpath 都不试**（`Z:\dead~1\f.md` 这类诱饵到此为止）。
    //   它必须问**这里的** `s` —— win32.resolve、`//?/` 剥离、`::$DATA` 剥离都已经做完，
    //   realpath 还没做（理由见上方那段「前筛必须落在零 I/O 串处理之后」）。
    if (/~\d/.test(s) && g2TailCouldBeLive(s)) s = g2LongPath(s, rp);
  } else if (/^\/(?!\/)/.test(s)) {
    try { s = path.posix.normalize(s); } catch (_) { /* 同上 */ }
  }
  return norm(s);
}

// 展开 + 归一 + 相对路径按 cwd 解析，**但不含 `g2Canon`**（那一步才有 realpath）。
// Git Bash 的 `/c/Users/...` 与 cygwin 的 `/cygdrive/c/...` 都要还原成盘符形态
// ——真语料里备份命令就是用 `/c/...` 写的。
//
// **为什么把这一层单独拆出来（#134）**：零 I/O 快筛必须看得见**归一前**的末段。
// 归一会解开 junction、改写最后一段，于是「末段像不像 `.claude`」这个问题在归一后
// 问出来的答案是错的。拆开之后两个深度都拿得到，快筛不必再假装归一不改末段。
// **#199 之后它还多担一件事**：它是 `g2Phases` 相①（归一前那一相）的输入，
// 也是 `g2TailCouldBeLive` 前筛的唯一喂料 —— 前筛**只吃归一前的串**。
function g2ResolvePre(raw, cwd, vars) {
  let s = g2Expand(raw, vars);
  if (!s) return "";
  s = norm(s);
  s = s.replace(/^\/cygdrive\/([A-Za-z])(?=\/|$)/, (m, d) => `${d}:`);
  s = s.replace(/^\/([A-Za-z])(?=\/)/, (m, d) => `${d}:`);
  const abs = /^[A-Za-z]:(\/|$)/.test(s) || /^\//.test(s);
  if (!abs) {
    try { s = norm(path.resolve(cwd || process.cwd(), s)); } catch (_) { /* 解析不了就按原样比 */ }
  }
  return s;
}
// 第四个参数 `rp` 由 `g2Phases` 给（相①=收集并抛 / 相②=查表）。**不传就是零 I/O**
// （`g2Canon` → `g2LongPath` → `G2_RP_NONE` → 按原样比），这个缺省方向是刻意的（#199）。
function g2Resolve(raw, cwd, vars, rp) {
  // ⑨：绝对路径此前直接 return，一步归一都没有 —— 两个分支现在都过这里。
  return g2Canon(g2ResolvePre(raw, cwd, vars), rp);
}

// 段内 token 化。与 shellSegmentsRaw 是两层不同的事：那层切**命令段**，这层切**参数**。
// 三个刻意的行为：
//   ① **引号里的 `>` 不算重定向**（`echo "a > b"` 只有两个 token）——重定向必须是**未被
//      引号包住**的，否则任何一句提到重定向的文本都会被当成写操作。
//   ② **双引号里的反斜杠不当转义吃掉**：Windows 路径 `"$env:USERPROFILE\.claude\settings.json"`
//      里的 `\.` 若按 POSIX 转义规则处理会变成 `.`，整条路径当场毁掉。只有 `\"` `\\` `\$`
//      这三种在 bash 双引号里真有转义语义的才剥。
//   ③ 重定向符前的 `1`/`2`/`&`（`2>` `&>>`）连着上一个 token，切之前先摘掉。
function g2Tokens(seg) {
  const src = String(seg || "");
  const out = [];
  let cur = "", quote = null, quoted = false;
  const flush = () => { if (cur !== "" || quoted) { out.push({ k: "arg", v: cur }); cur = ""; quoted = false; } };
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (quote) {
      if (c === "\\" && quote === '"' && (src[i + 1] === '"' || src[i + 1] === "\\" || src[i + 1] === "$")) {
        cur += src[++i]; continue;
      }
      if (c === quote) { quote = null; continue; }
      cur += c; continue;
    }
    if (c === '"' || c === "'") { quote = c; quoted = true; continue; }
    if (c === ">") {
      cur = cur.replace(/[\d&]+$/, "");
      flush();
      if (src[i + 1] === ">") i++;
      out.push({ k: "redir" });
      continue;
    }
    if (c === "<") { flush(); if (src[i + 1] === "<") i++; out.push({ k: "in" }); continue; }
    if (/\s/.test(c)) { flush(); continue; }
    cur += c;
  }
  flush();
  return out;
}

// `(Join-Path A B [C])` 折成一个 token。真语料里这是本机最常见的路径拼法
// （`Join-Path $env:USERPROFILE '.claude\projects'` 在转录里到处都是），不折就解不出。
// 只认**带括号**的形态：裸 `$p = Join-Path a b` 是表达式右值，见头注 G2 漏报面②。
function g2FoldJoinPath(seg) {
  let s = String(seg || "");
  for (let n = 0; n < 4; n++) {
    const m = /\(\s*Join-Path\s+((?:"[^"]*"|'[^']*'|[^\s()]+)(?:\s+(?:"[^"]*"|'[^']*'|[^\s()]+))+)\s*\)/i.exec(s);
    if (!m) break;
    const parts = (m[1].match(/"[^"]*"|'[^']*'|\S+/g) || [])
      .map((x) => x.replace(/^(["'])([\s\S]*)\1$/, "$2"));
    s = s.slice(0, m.index) + '"' + parts.join("/") + '"' + s.slice(m.index + m[0].length);
  }
  return s;
}

// 同一条命令里的**字面量**赋值：`$p = "…"`（PowerShell）/ `P=…`（bash 独立段）。
// 只做一层、只认字面量右值——表达式右值不解析（头注 G2 漏报面②，别读成已覆盖）。
function g2VarMap(segs) {
  const map = new Map();
  for (const raw of segs) {
    const s = String(raw || "").trim();
    const m = /^\$([A-Za-z_]\w*)\s*=\s*("[^"]*"|'[^']*'|\S+)$/.exec(s)
           || /^([A-Za-z_]\w*)=("[^"]*"|'[^']*'|\S+)$/.exec(s);
    if (m) map.set("$" + m[1], m[2].replace(/^(["'])([\s\S]*)\1$/, "$2"));
  }
  return map;
}

